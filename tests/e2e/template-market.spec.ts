import { expect, test } from '@playwright/test'
import JSZip from 'jszip'

test('offers original school documents and preserves keyboard and small-screen navigation', async ({ page, request }) => {
  await page.goto('/research')
  await page.getByRole('link', { name: 'Paper templates', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Paper templates', exact: true })).toBeVisible()
  const cards = page.getByRole('list', { name: 'Template results' })
  const details = page.getByRole('complementary', { name: 'Template details' })
  await page.getByRole('button', { name: 'Universities', exact: true }).click()
  await expect(cards.getByRole('button')).toHaveCount(10)
  await expect(cards.getByRole('button', { name: '南京邮电大学 · 学术硕士（人文社科）' })).toBeVisible()
  await page.getByLabel('Language', { exact: true }).selectOption('English')
  await expect(cards.getByRole('button', { name: 'MIT Thesis' })).toBeVisible()
  await expect(cards.getByRole('button')).toHaveCount(1)
  await page.getByRole('button', { name: 'Journals', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search templates' }).fill('Science')
  await expect(cards.getByRole('button', { name: 'Science · AAAS' })).toBeVisible()
  await expect(details.getByRole('link', { name: 'View source preview' })).toBeVisible()
  await page.getByRole('searchbox', { name: 'Search templates' }).clear()
  await page.getByRole('button', { name: 'Universities', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(details).toBeHidden()
  const bachelor = cards.getByRole('button', { name: '上海电力大学 · 本科毕业设计' })
  await bachelor.press('Enter')
  await expect(details).toContainText('官方封面中的校徽')
  expect((await request.get('/template-assets/suep-undergraduate-emblem.png')).headers()['content-type']).toBe('image/png')
  await expect(details.getByRole('link', { name: /2026-10-13 版封面/ })).toHaveAttribute('href', /^https:\/\/xxgk\.shiep\.edu\.cn\/.+\.rar$/)
  await expect(details.getByRole('link', { name: /原创性及使用授权声明/ })).toHaveAttribute('href', /^https:\/\/dqxb\.shiep\.edu\.cn\/.+\.doc$/)
  await expect(details.getByRole('link', { name: /学校格式示范文本/ })).toBeVisible()
  await expect(details.getByRole('link', { name: /学校撰写规范/ })).toBeVisible()
  await expect(details.getByRole('button', { name: '使用模板', exact: true })).toBeEnabled()
  await expect(details).toContainText('已回归专用 Word 导入')
  await bachelor.press('ArrowRight')
  const masters = cards.getByRole('button', { name: '上海电力大学 · 硕士学位论文' })
  await expect(masters).toBeFocused()
  await masters.press('Enter')
  await expect(details).toBeVisible()
  await expect(details.getByRole('link', { name: /研究生院范本/ })).toHaveAttribute('href', /^https:\/\/yjsc\.shiep\.edu\.cn\/.+\.doc$/)
  await expect(details.getByRole('link', { name: '查看学校 PDF 原件' })).toBeVisible()
  await expect(details.getByRole('button', { name: '使用模板', exact: true })).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByRole('button', { name: 'Journals', exact: true }).click()
  await cards.getByRole('button', { name: 'ACM Journal Manuscript' }).click()
  await expect(details.getByRole('link', { name: '查看模板来源' })).toHaveAttribute(
    'href', 'https://www.overleaf.com/latex/templates/acm-journals-primary-article-template/cpkjqttwbshg',
  )
  await expect(details.getByRole('button', { name: '使用模板', exact: true })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/research?section=templates&category=school&template=njupt-humanities-masters&manage=1')
  await expect(details.getByRole('button', { name: '检查官方原件更新' })).toBeVisible()
  await expect(details).toBeFocused()
})

test('saves a ZIP and project as local templates, reuses and removes a template independently of the project', async ({ page }) => {
  const archive = new JSZip()
  archive.file('main.tex', '\\documentclass{article}\n\\begin{document}\nLocal template marker\n\\end{document}')
  archive.file('private.txt', 'Excluded from local template')
  await page.goto('/research?section=templates')
  await page.getByLabel('Choose template ZIP').setInputFiles({ name: 'Local sample.zip', mimeType: 'application/zip',
    buffer: await archive.generateAsync({ type: 'nodebuffer' }) })
  await page.getByRole('checkbox', { name: 'private.txt' }).uncheck()
  await page.getByRole('button', { name: 'Save template', exact: true }).click()
  const details = page.getByRole('complementary', { name: 'Template details' })
  await expect(details.getByRole('heading', { name: 'Local sample' })).toBeVisible()
  await details.getByRole('button', { name: 'Rename', exact: true }).click()
  await page.getByRole('textbox', { name: 'Template name' }).fill('Local source')
  await page.getByRole('button', { name: 'Save name' }).click()
  const [download] = await Promise.all([
    page.waitForEvent('download'), details.getByRole('button', { name: 'Download ZIP' }).click(),
  ])
  expect(download.suggestedFilename()).toBe('Local source.zip')
  await details.getByRole('button', { name: '使用模板', exact: true }).click()
  await page.getByRole('textbox', { name: 'Project name' }).fill('Copy of source')
  await page.getByRole('button', { name: 'Create project' }).click()
  const source = page.getByRole('region', { name: 'Source editor' })
  await expect(source.locator('.view-lines')).toContainText('Local template marker')
  await expect(page.getByRole('button', { name: 'private.txt', exact: true })).toHaveCount(0)
  const copyUrl = page.url()
  await page.getByRole('button', { name: 'Project menu' }).click()
  await page.getByRole('menuitem', { name: 'Save as template' }).click()
  await page.getByRole('textbox', { name: 'Template name' }).fill('Saved from project')
  await page.getByRole('button', { name: 'Save template', exact: true }).click()
  await expect(page.getByText('Template saved to My templates.')).toBeVisible()

  await page.goto('/research?section=templates&category=mine')
  await page.getByRole('button', { name: 'Local source', exact: true }).click()
  await details.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Delete template' }).click()
  await expect(page.getByRole('button', { name: 'Local source', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Saved from project', exact: true })).toBeVisible()
  await page.goto(copyUrl)
  await expect(source.locator('.view-lines')).toContainText('Local template marker')
})

test('rejects a mismatched publisher archive from the market', async ({ page }) => {
  await page.goto('/research?section=templates&template=plos-one')
  const details = page.getByRole('complementary', { name: 'Template details' })
  await details.getByRole('button', { name: '手动上传原件', exact: true }).click()
  await page.getByRole('textbox', { name: 'Project name' }).fill('PLOS draft')
  await page.getByLabel('Publisher template ZIP').setInputFiles({
    name: 'unrelated.zip', mimeType: 'application/zip', buffer: Buffer.from('not a template'),
  })
  await page.getByRole('button', { name: 'Create project', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'This ZIP does not match' })).toBeVisible()
  await expect(page).toHaveURL(/section=templates/)
})
