test('exports a current recovery backup from Archive and restores the saved draft as a copy', async ({ page, context }, info) => {
  await page.goto('/research')
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await page.getByRole('textbox', { name: 'Project name' }).fill('Archived manuscript')
  await page.getByRole('radio', { name: 'English article', exact: true }).check()
  await page.getByRole('button', { name: 'Create project' }).click()
  await expect(source(page).locator('.view-lines')).toContainText('Your paper title')
  const original = page.url()
  await appendDraft(page, '% Persisted draft from the archive')
  await backToProjects(page)
  const details = page.getByRole('complementary', { name: 'Project details' })
  await details.getByRole('button', { name: 'Archive', exact: true }).click()
  await page.getByRole('button', { name: 'Archived', exact: true }).click()
  const observer = await context.newPage()
  await observer.goto('/research')
  await observer.getByRole('button', { name: 'Archived', exact: true }).click()
  const observedDetails = observer.getByRole('complementary', { name: 'Project details' })
  await expect(observedDetails.getByText('No backup export recorded for this browser')).toBeVisible()
  const [download] = await Promise.all([
    page.waitForEvent('download'), details.getByRole('button', { name: 'Download recovery backup' }).click(),
  ])
  expect(download.suggestedFilename()).toBe('Archived manuscript.research-canvas')
  const path = info.outputPath(download.suggestedFilename())
  await download.saveAs(path)
  await expect(details.getByText('Complete recovery backup matches the saved project')).toBeVisible()
  await expect(observedDetails.getByText('Complete recovery backup matches the saved project')).toBeVisible()
  const zip = await JSZip.loadAsync(await readFile(path))
  const manifest = JSON.parse(await zip.file('project.json')!.async('text'))
  expect(manifest.writing.drafts['main.tex'].text).toContain('Persisted draft from the archive')
  expect(manifest.history).toHaveProperty('publication')
  expect(manifest.history).toHaveProperty('snapshots')

  await page.getByLabel('Choose project ZIP or backup').setInputFiles(path)
  await page.getByRole('button', { name: 'Import as new project' }).click()
  await expect(page).not.toHaveURL(original)
  await expect(source(page).locator('.view-lines')).toContainText('Persisted draft from the archive')
  await expect(observedDetails.getByText('Archived manuscript', { exact: true })).toBeVisible()
})

test('uses the same workbench palette on the library, Canvas and Writing at a small viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/research')
  const libraryBar = page.locator('main > header')
  const libraryColor = await libraryBar.evaluate(element => getComputedStyle(element).backgroundColor)
  expect(libraryColor).toBe('rgb(255, 255, 255)')
  const newProject = page.getByRole('button', { name: 'New project' })
  await expect(newProject).toHaveCSS('background-color', 'rgb(90, 59, 192)')
  await newProject.click()
  await page.getByRole('textbox', { name: 'Project name' }).fill('Shared palette')
  const create = page.getByRole('button', { name: 'Create project' })
  await expect(create).toHaveCSS('background-color', 'rgb(90, 59, 192)')
  await create.click()
  const toolbar = page.locator('header[aria-label="Project"]')
  await expect(toolbar).toHaveCSS('background-color', libraryColor)
  await page.getByRole('button', { name: 'Writing', exact: true }).click()
  await expect(source(page)).toBeVisible()
  await expect(toolbar).toHaveCSS('background-color', libraryColor)
  await expect(page.getByRole('button', { name: 'Compile PDF', exact: true })).toHaveCSS('background-color', 'rgb(90, 59, 192)')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await backToProjects(page)
  await expect(libraryBar).toHaveCSS('background-color', libraryColor)
})

test('reports unavailable storage without showing an empty project list', async ({ page }) => {
  await page.addInitScript(() => {
    indexedDB.open = () => { throw new DOMException('Storage disabled', 'SecurityError') }
  })
  await page.goto('/research')
  await expect(page.getByRole('alert').filter({ hasText: 'Local project storage could not be opened.' })).toBeVisible()
  await expect(page.getByRole('searchbox', { name: 'Search projects' })).toBeDisabled()
  await expect(page.getByText('Create a project or import a LaTeX ZIP or Research Canvas backup.')).toHaveCount(0)
})

test('creates, renames, archives, trashes and restores a project while preserving its address', async ({ page }) => {
  await page.goto('/research')
  await page.getByRole('button', { name: 'New project' }).click()
  await page.getByRole('textbox', { name: 'Project name' }).fill('New paper')
  await page.getByRole('button', { name: 'Create project' }).click()
  await expect(page.getByRole('heading', { name: 'New paper', exact: true })).toBeVisible()
  await expect(page).toHaveURL(/project=[a-f0-9-]+/)
  const created = page.url()
  await page.getByRole('button', { name: 'Writing', exact: true }).click()
  await backToProjects(page)
  await page.getByRole('button', { name: 'Rename', exact: true }).click()
  await page.getByRole('textbox', { name: 'Project name' }).fill('Renamed paper')
  await page.getByRole('button', { name: 'Save name' }).click()
  await expect(page.getByRole('link', { name: 'Open Renamed paper' })).toHaveAttribute('href', /view=write/)
  await page.getByRole('button', { name: 'Archive', exact: true }).click()
  await page.getByRole('button', { name: 'Archived', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Renamed paper' })).toBeVisible()
  await page.getByRole('button', { name: 'Move to Trash' }).click()
  await page.getByRole('button', { name: 'Trash', exact: true }).click()
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('link', { name: 'Open Renamed paper' }).click()
  await expect(page.getByRole('heading', { name: 'Renamed paper', exact: true })).toBeVisible()
  await expect(page).toHaveURL(created + '&view=write')
  await expect(source(page)).toBeVisible()
  await page.getByRole('button', { name: 'Canvas', exact: true }).click()
  const viewport = page.locator('.react-flow__viewport:visible')
  const prior = await viewport.evaluate(element => getComputedStyle(element).transform)
  await page.getByRole('button', { name: /^zoom in$/i }).click()
  await expect.poll(() => viewport.evaluate(element => getComputedStyle(element).transform)).not.toBe(prior)
  await expect.poll(() => viewport.evaluate(element => new DOMMatrix(getComputedStyle(element).transform).a)).toBeCloseTo(1.2, 2)
  const viewportBefore = await viewport.evaluate(element => getComputedStyle(element).transform)
  await backToProjects(page)
  await page.getByRole('link', { name: 'Open Renamed paper' }).click()
  await expect(page).toHaveURL(created)
  await expect(viewport).toHaveCSS('transform', viewportBefore)
})
