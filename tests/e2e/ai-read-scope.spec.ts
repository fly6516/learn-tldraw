import { expect, test } from '@playwright/test'
import { morningWalkZip } from '../fixtures/morning-walk'

test('previews actual model context and leaves excluded bytes out of requests after reload', async ({ page }) => {
  await page.goto('/research')
  await page.getByLabel('Choose project ZIP or backup').setInputFiles({
    name: 'Morning Walk Study.zip', mimeType: 'application/zip', buffer: await morningWalkZip(),
  })
  await page.getByRole('button', { name: 'Writing AI', exact: true }).click()
  const prompt = page.getByRole('textbox', { name: 'Message Writing AI' })
  await prompt.fill('Show me the contents of this example. Earlier message marker: local-history-412.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Assistant' }).last()).toContainText('Fixture response')

  await page.getByRole('button', { name: 'methods.tex', exact: true }).click()
  const editor = page.getByRole('textbox', { name: 'Project source editor' })
  await editor.press('Control+End')
  await page.keyboard.insertText('\n% shared local draft marker\n')
  await page.getByRole('button', { name: 'results.tex', exact: true }).click()
  await editor.press('Control+End')
  await page.keyboard.insertText('\n\\privateDiagnosticMarker\n')
  await page.getByRole('button', { name: 'Compile PDF', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Writing tools' })).toContainText('Undefined control sequence')
  await page.getByRole('button', { name: 'methods.tex', exact: false }).first().click()
  await page.getByRole('button', { name: /^Read exclusions/ }).click()
  await page.getByRole('textbox', { name: 'Excluded project paths' }).fill('sections/results.tex\ndata/')
  await page.getByRole('button', { name: 'Save read exclusions' }).click()
  const check = async () => {
    await prompt.fill('Summarize the available chapters.')
    await page.getByRole('button', { name: 'Review context' }).click()
    const preview = page.getByRole('dialog', { name: 'Review model context' })
    await expect(preview).toContainText('Local test model')
    await expect(preview).toContainText('sections/methods.tex · Local draft')
    await expect(preview).toContainText('Earlier chat messages withheld.')
    await expect(preview).not.toContainText('sections/results.tex')
    await expect(preview).not.toContainText('data/sessions.csv')
    const call = page.waitForRequest(request => request.url().endsWith('/api/latex/chat'))
    await preview.getByRole('button', { name: 'Send reviewed request' }).click()
    const body = (await call).postDataJSON()
    expect(body.expectedRecipient).toBe('Local test model')
    expect(body.messages).toEqual([{ role: 'user', text: 'Summarize the available chapters.' }])
    expect(body.source.compiler).toEqual({ state: 'unavailable', diagnostics: [], log: '' })
    expect(JSON.stringify(body)).not.toContain('privateDiagnosticMarker')
    expect(body.source.source).toContain('shared local draft marker')
    expect(body.source.context.map((file: { path: string }) => file.path)).not.toContain('sections/results.tex')
    expect(body.scope).not.toContain('sections/results.tex')
    expect(body.attachments.csv).toHaveLength(0)
    expect(body.attachments.entries.some((item: { path: string }) => item.path.startsWith('data/'))).toBe(false)
    const response = page.getByRole('article', { name: 'Assistant' }).last()
    await expect(response).toContainText('Fixture response')
    await response.getByText('Model context sent', { exact: true }).click()
    await expect(response).toContainText('Local test model')
    await expect(response).toContainText('0 earlier chat messages sent.')
    await expect(response.getByRole('list', { name: 'Model context files' })).not.toContainText('sections/results.tex')
  }
  await check()
  await page.reload()
  await page.getByRole('button', { name: 'Writing AI', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Read exclusions · 2' })).toBeVisible()
  await expect(page.getByRole('article', { name: 'Assistant' }).last().getByText('Model context sent', { exact: true })).toBeVisible()
  await check()
})
