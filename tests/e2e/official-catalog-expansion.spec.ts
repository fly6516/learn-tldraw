import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import JSZip from 'jszip'
import { templateCatalog } from '../../src/lib/project/template-catalog'
import { archiveSubmission, compileProject, confirmTemplatePublication, loadCandidate, openLayoutReport, publisherFile, replaceProjectSource,
  reviewArchive, saveCompiledPdf, useOfficialTemplate } from './support/official-template'

const fixtures = process.env.RESEARCH_OFFICIAL_EXPANSION_FIXTURES
const catalog = (category: string, template: string) => `/research?section=templates&category=${category}&template=${template}&manage=1`

async function savePdf(page: Page, path: string) {
  await page.getByRole('button', { name: 'Compile PDF', exact: true }).click()
  const download = page.getByRole('region', { name: 'PDF Preview' }).getByRole('link', { name: 'Download PDF' })
  await expect(download).toBeVisible({ timeout: 60_000 })
  const saved = page.waitForEvent('download')
  await download.click()
  await (await saved).saveAs(path)
}

test('checks the official NJUPT source and generates a PDF with an independent humanities manuscript', async ({ page }, info) => {
  test.skip(!fixtures, 'Requires the official file, guide and independent manuscript.')
  test.setTimeout(150_000)
  await page.goto(catalog('school', 'njupt-humanities-masters'))
  const details = page.getByRole('complementary', { name: 'Template details' })
  await details.getByRole('button', { name: '检查官方原件更新' }).click()
  await expect(details.getByRole('status')).toContainText('所检查的官方原件与当前发布版一致。', { timeout: 25_000 })
  await details.getByRole('button', { name: '手动上传原件', exact: true }).click()
  const builder = page.getByRole('dialog', { name: '从 Word 生成模板' })
  await builder.getByLabel('Word 样例').setInputFiles(join(fixtures!, 'njupt-humanities.doc'))
  await builder.getByLabel('学校撰写规范（选填）').setInputFiles(join(fixtures!, 'requirements.pdf'))
  await builder.getByRole('button', { name: '生成版式配置' }).click()
  await expect(builder.getByLabel('纸张')).toHaveValue('a4')
  const conflicts = builder.getByText('样例与规范不一致，请选择').locator('..')
  while (await conflicts.count()) await conflicts.first().getByRole('button', { name: '采用规范' }).click()
  await builder.getByLabel('固定页眉文字').fill('南京邮电大学硕士研究生学位论文')
  await builder.getByLabel('一级标题起页方式').selectOption('new-page')
  await builder.getByLabel('模板名称').fill('南邮人文社科 · 独立稿验收')
  const compilation = page.waitForResponse(response => response.url().includes('/api/latex/compile?'))
  await builder.getByRole('button', { name: '编译 PDF 预览' }).click()
  const compiled = await compilation
  expect(compiled.ok(), compiled.ok() ? undefined : (await compiled.json()).error).toBe(true)
  await expect(builder.getByRole('link', { name: '下载预览 PDF' })).toBeVisible({ timeout: 60_000 })
  await builder.getByRole('button', { name: '保存到我的模板' }).click()
  await page.getByRole('button', { name: '使用模板', exact: true }).click()
  const importer = page.getByRole('dialog', { name: 'Import Word to TeX' })
  await importer.getByLabel('Project name').fill('南邮人文社科 · PDF 验收')
  await importer.getByLabel('Word manuscript').setInputFiles(join(fixtures!, 'humanities-manuscript.docx'))
  const imported = page.waitForResponse(response => response.url().endsWith('/api/word/import') && response.request().method() === 'POST')
  await importer.getByRole('button', { name: 'Create TeX project' }).click()
  const response = await imported
  expect(response.ok(), response.ok() ? undefined : await response.text()).toBe(true)
  const archive = await JSZip.loadAsync(await response.body())
  const manuscript = await archive.file('manuscript.tex')!.async('string')
  expect(manuscript).toContain('社区数字档案')
  expect(manuscript).not.toContain('学术学位硕士研究生学位论文模板')
  expect(manuscript).toContain('参考文献')
  const layoutSource = await archive.file('word-layout.tex')!.async('string')
  const corrected = manuscript.replace('{[}7{]}', '{[}1{]}')
  const wrongCaption = manuscript.replace(/按图\s*1\.1/, '按图 9.9')
  const wrongFooter = layoutSource.replace('\\selectfont\\thepage', '\\selectfont 7')
  expect(corrected).not.toBe(manuscript)
  expect(wrongCaption).not.toBe(manuscript)
  expect(wrongFooter).not.toBe(layoutSource)
  const edit = async (file: string, content: string) => {
    await page.getByRole('complementary', { name: 'Project navigation' }).getByTitle(file, { exact: true }).click()
    await page.getByRole('textbox', { name: 'Project source editor' }).press('Control+a')
    await page.keyboard.insertText(content)
  }
  const compile = async () => {
    const compiled = page.waitForResponse(result => result.url().includes('/api/latex/compile?'))
    await page.getByRole('button', { name: 'Compile PDF', exact: true }).click()
    const response = await compiled
    expect(response.ok(), response.ok() ? undefined : (await response.json()).error).toBe(true)
    await expect(page.getByText(/Last successful compile.*Up to date/)).toBeVisible({ timeout: 60_000 })
  }
  await edit('manuscript.tex', corrected)
  await savePdf(page, info.outputPath('njupt-humanities.pdf'))
  await page.getByRole('button', { name: '提交前版式检查' }).click()
  const report = page.getByRole('dialog', { name: '提交前版式检查' })
  const row = (label: string) => report.getByRole('listitem').filter({ hasText: label })
  await expect(report.getByRole('listitem').filter({ hasText: '纸张尺寸' })).toContainText('纸张为 A4')
  await expect(report.getByRole('listitem').filter({ hasText: '南邮封面' })).toContainText('待人工核对')
  await expect(row('正文页边距')).toContainText('已核对')
  await expect(row('目录页码').filter({ hasText: '发现问题' })).toHaveCount(0)
  await expect(row('参考文献缺项')).toContainText('已核对')
  await report.getByRole('button', { name: 'Close' }).click()

  await edit('manuscript.tex', wrongCaption)
  await edit('word-layout.tex', wrongFooter)
  await compile()
  await page.getByRole('button', { name: '提交前版式检查' }).click()
  await expect(row('目录页码').filter({ hasText: '发现问题' }).first()).toContainText('目录印刷页码')
  await expect(row('图表题注与引用')).toContainText('图9-9')
  await expect(row('参考文献缺项')).toContainText('引文 7')
  await row('图表题注与引用').getByRole('button', { name: /manuscript\.tex:\d+/ }).click()
  await expect(report).toBeHidden()

  await edit('manuscript.tex', corrected)
  await edit('word-layout.tex', layoutSource)
  await compile()
  await page.getByRole('button', { name: '提交前版式检查' }).click()
  await expect(row('目录页码').filter({ hasText: '发现问题' })).toHaveCount(0)
  await expect(row('图表题注与引用')).toContainText('已核对')
  await expect(row('参考文献缺项')).toContainText('已核对')
})

test('uses the JMLR pinned ZIP, revisits the archived report after an upstream update, and transfers the release', async ({ page, browser }, info) => {
  test.skip(!fixtures, 'Requires the official JMLR source ZIP.')
  test.setTimeout(180_000)
  const card = catalog('journal', 'jmlr')
  const entry = templateCatalog.find(item => item.id === 'jmlr')
  if (entry?.delivery !== 'archive' || entry.workflow?.kind !== 'zip' || !entry.workflow.upstream) throw new Error('Missing JMLR archive sources.')
  const { original: pinned, upstream, compile } = entry.workflow
  await publisherFile(join(fixtures!, 'jmlr-pinned.zip'), pinned.sha256)
  const source = await publisherFile(join(fixtures!, 'jmlr.zip'), entry.template.sha256)
  const manuscript = await readFile(join('tests', 'e2e', 'fixtures', 'official-template-acceptance', 'jmlr-manuscript.tex'), 'utf8')
  const original = await JSZip.loadAsync(source)
  original.file(entry.template.mainFile, manuscript.replaceAll('Independent Support Set Study', 'Updated Support Set Study'))
  const candidate = await original.generateAsync({ type: 'nodebuffer' })
  await page.goto(card)
  const details = page.getByRole('complementary', { name: 'Template details' })
  const checked = page.waitForResponse(response => response.url().includes('/api/templates/source?id=jmlr'))
  await details.getByRole('button', { name: '检查官方原件更新' }).click()
  expect(await (await checked).json()).toMatchObject({ sha256: upstream.sha256, matchesBaseline: true, url: upstream.url })
  await expect(details.getByRole('status')).toContainText('所检查的官方原件与当前发布版一致。')
  await expect(details.getByRole('button', { name: '载入官方原件验收' })).toHaveCount(0)
  await expect(details.getByRole('button', { name: '使用模板', exact: true })).toBeVisible()
  await useOfficialTemplate(page, pinned.sha256)
  const baseline = page.getByRole('dialog', { name: 'Create project from template' })
  await baseline.getByLabel('Project name').fill('JMLR · Official snapshot')
  await expect(baseline.getByLabel('Publisher template ZIP')).toHaveCount(0)
  await baseline.getByRole('button', { name: 'Create project' }).click()
  await page.waitForURL(url => url.searchParams.has('project'))
  const oldUrl = page.url()
  await savePdf(page, info.outputPath('jmlr-official-snapshot.pdf'))
  await replaceProjectSource(page, compile.mainFile, manuscript)
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('All changes saved to project')).toBeVisible()
  await compileProject(page)
  const pageOne = page.getByRole('region', { name: 'Compiled PDF, page 1', exact: true })
  await expect(pageOne).toContainText('Independent Support Set Study')
  await expect(pageOne).toContainText('Chow and Liu')
  await saveCompiledPdf(page, info.outputPath('jmlr-independent.pdf'))
  const report = await openLayoutReport(page)
  await expect(report.getByRole('listitem').filter({ hasText: '参考文献缺项' })).toContainText('已核对')
  await report.getByRole('button', { name: 'Close' }).click()
  await archiveSubmission(page, 'JMLR 固定版报告', 'JMLR 投稿阶段要求')

  await page.goto(card)
  await loadCandidate(page, entry.id, upstream.url, entry.template.version, 'jmlr-qa.zip', candidate)
  const verify = page.getByRole('dialog', { name: '验收模板候选' })
  await verify.getByLabel('候选版本号').fill('f413f63-qa.1')
  await expect(verify.getByLabel('候选官方 ZIP')).toHaveCount(0)
  await expect(verify.getByRole('button', { name: '发布新版本' })).toHaveCount(0)
  await verify.getByRole('button', { name: '编译候选' }).click()
  await expect(verify.getByRole('link', { name: '查看候选 PDF' })).toBeVisible({ timeout: 60_000 })
  await verify.getByRole('button', { name: '发布新版本' }).click()
  const confirm = page.getByRole('alertdialog', { name: '确认发布模板版本' })
  await confirm.getByRole('button', { name: '返回候选预览' }).click()
  await expect(page.getByText('当前发布版 ' + entry.template.version, { exact: true })).toBeVisible()
  await expect(verify.getByRole('link', { name: '查看候选 PDF' })).toBeVisible()
  await verify.getByRole('button', { name: '发布新版本' }).click()
  await confirmTemplatePublication(page, 'f413f63-qa.1', entry.template.version)
  await expect(verify).toBeHidden()
  await page.unrouteAll({ behavior: 'wait' })
  await page.getByRole('button', { name: '检查官方原件更新' }).click()
  await expect(page.getByRole('complementary', { name: 'Template details' }).getByRole('status'))
    .toContainText('发现不同的官方原件', { timeout: 25_000 })
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出所选版本' }).click()
  const transfer = info.outputPath('jmlr.release.zip')
  await (await download).saveAs(transfer)

  const context = await browser.newContext()
  try {
    const fresh = await context.newPage()
    await fresh.goto(new URL(card, page.url()).href)
    await expect(fresh.getByText('当前发布版 f413f63', { exact: true })).toBeVisible()
    const corrupted = await JSZip.loadAsync(await readFile(transfer))
    corrupted.file('payload.zip', 'corrupted')
    await fresh.getByLabel('官方模板版本包').setInputFiles({
      name: 'corrupted.zip', mimeType: 'application/zip', buffer: await corrupted.generateAsync({ type: 'nodebuffer' }),
    })
    await expect(fresh.getByText('版本包内容校验失败。', { exact: true })).toBeVisible()
    await fresh.getByLabel('官方模板版本包').setInputFiles(transfer)
    const confirmation = fresh.getByRole('dialog', { name: '导入官方模板版本包' })
    await expect(confirmation).toContainText('原浏览器验收记录')
    await expect(fresh.getByText('当前发布版 f413f63', { exact: true })).toBeVisible()
    await confirmation.getByRole('button', { name: '导入并启用' }).click()
    await expect(fresh.getByText('当前发布版 f413f63-qa.1', { exact: true })).toBeVisible()
    await fresh.getByRole('button', { name: '使用模板', exact: true }).click()
    const create = fresh.getByRole('dialog', { name: 'Create project from template' })
    await create.getByLabel('Project name').fill('JMLR · PDF acceptance')
    await create.getByRole('button', { name: 'Create project' }).click()
    await savePdf(fresh, info.outputPath('jmlr.pdf'))
    await expect(fresh.getByRole('region', { name: 'Compiled PDF, page 1', exact: true })).toContainText('Updated Support Set Study')
    await fresh.getByRole('button', { name: '提交前版式检查' }).click()
    const report = fresh.getByRole('dialog', { name: '提交前版式检查' })
    await expect(report.getByRole('listitem').filter({ hasText: 'JMLR 文档类与样式' })).toContainText('已核对')
    await expect(report.getByRole('listitem').filter({ hasText: 'JMLR 投稿阶段要求' })).toContainText('待人工核对')
  } finally {
    await context.close()
  }
  await reviewArchive(page, oldUrl, 'JMLR 固定版报告', entry.id + ' · ' + entry.template.version,
    async archived => {
      await expect(archived).toContainText('JMLR 文档类与样式')
      await expect(archived).toContainText('原件 SHA-256 ' + pinned.sha256)
    })
  await compileProject(page)
  await expect(pageOne).toContainText('Independent Support Set Study')
})
