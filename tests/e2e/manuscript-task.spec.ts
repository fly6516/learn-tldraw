test('repairs a failed manuscript, checks a conflict and saves only the exact verified files', async ({ page }) => {
  test.setTimeout(120_000)
  await installPaper(page)
  const editor = page.getByRole('textbox', { name: 'Project source editor' })
  const source = page.getByRole('region', { name: 'Source editor' }).locator('.view-lines')
  const file = (name: string) => page.getByRole('button', { name: new RegExp(`^${name}\\.tex\\b`) })
  const task = page.getByRole('region', { name: 'Manuscript task' })
  const review = page.getByRole('dialog', { name: 'Review manuscript task' })
  const openReview = () => task.getByRole('button', { name: 'Review and save task' }).click()
  const verify = () => review.getByRole('button', { name: 'Verify manuscript' }).click()
  const save = review.getByRole('button', { name: 'Save verified files' })
  const draft = '\\authorUnrelatedCommand'
  await editor.press('Control+Home')
  await page.keyboard.insertText(draft + '\n')
  await expect(file('main').getByLabel('Unsaved')).toBeVisible()

  await page.getByRole('combobox', { name: 'Approval mode' }).selectOption('full')
  await page.getByRole('button', { name: 'Grant full draft access', exact: true }).click()
  await page.getByRole('textbox', { name: 'Message Writing AI' }).fill('Test: revise the complete manuscript and include a compiler failure')
  await page.getByRole('button', { name: 'Plan writing task' }).click()
  await task.getByRole('button', { name: 'Continue task' }).click()
  await expect(task.getByRole('status')).toContainText('4 of 4 files applied')
  await openReview()
  await verify()
  await expect(review.getByRole('status')).toContainText('Manuscript verification failed.')
  await expect(save).toBeDisabled()
  const queue = review.getByRole('region', { name: 'Manuscript review queue' })
  const diagnostic = queue.getByRole('button', { name: /Compile error.*sections\/results\.tex/ }).first()
  await review.getByRole('button', { name: 'Next review item' }).click()
  await expect(diagnostic).toHaveAttribute('aria-pressed', 'true')
  await queue.getByRole('button', { name: 'Open source for selected item' }).click()
  await expect(source).toContainText('\\undefinedFixtureCommand')
  await expect(file('methods').getByLabel('Unsaved')).toBeVisible()
  await page.getByRole('button', { name: 'Back to manuscript review' }).click()
  await expect(diagnostic).toBeFocused()
  await review.getByRole('button', { name: 'Repair affected files with AI' }).click()
  const repair = page.getByRole('region', { name: 'Source change proposal' }).last()
  await expect(repair.getByRole('button', { name: 'Apply to drafts' })).toBeVisible()
  await expect(repair.getByText('sections/results.tex', { exact: true })).toBeVisible()
  await expect(repair.getByText('sections/methods.tex', { exact: true })).toHaveCount(0)
  await repair.getByRole('button', { name: 'Apply to drafts' }).click()
  await expect(source).toContainText(testResultEdit)
  await expect(source).not.toContainText('\\undefinedFixtureCommand')

  await file('methods').click()
  await editor.press('Control+End')
  await page.keyboard.insertText('Author clarification after the AI batch.\n')
  await expect(source).toContainText('Author clarification')
  await openReview()
  const includeMethods = review.getByRole('checkbox', { name: 'Include sections/methods.tex' })
  await expect(includeMethods).toBeDisabled()
  await expect(queue.getByRole('button', { name: /Author draft conflict.*sections\/methods\.tex/ })).toBeVisible()
  await review.getByRole('button', { name: 'sections/methods.tex', exact: true }).click()
  await expect(review.getByRole('region', { name: 'Author changes conflict' })).toBeVisible()
  await review.getByRole('button', { name: 'Include current author version' }).click()
  await expect(includeMethods).toBeChecked()
  let capture!: (buffer: number[]) => void
  const compiled = new Promise<number[]>(resolve => { capture = resolve })
  await page.exposeFunction('captureManuscriptArchive', capture)
  await page.evaluate(() => {
    const original = window.fetch
    window.fetch = async (input, init) => {
      if (typeof input === 'string' && input.startsWith('/api/latex/compile?') && init?.body instanceof Blob) {
        const archive = await init.body.arrayBuffer()
        const bridge = window as Window & { captureManuscriptArchive?: (buffer: number[]) => Promise<void> }
        await bridge.captureManuscriptArchive?.(Array.from(new Uint8Array(archive)))
      }
      return original(input, init)
    }
  })
  await verify()
  const zip = await JSZip.loadAsync(new Uint8Array(await compiled))
  expect(await zip.file('main.tex')!.async('string')).not.toContain(draft)
  expect(await zip.file('sections/methods.tex')!.async('string')).toContain('Author clarification')
  expect(await zip.file('sections/results.tex')!.async('string')).toContain(testResultEdit)
  await expect(review.getByRole('status')).toContainText('Manuscript verification passed.')
  await includeMethods.click()
  await expect(save).toBeDisabled()
  await expect(review.getByRole('status')).toContainText('out of date')
  await includeMethods.click()
  await save.click()
  await expect(task.getByText('4 task files saved together.')).toBeVisible()
  await expect(file('methods').getByLabel('Unsaved')).toHaveCount(0)
  await expect(file('main').getByLabel('Unsaved')).toBeVisible()

  await page.reload()
  await page.getByRole('button', { name: 'Writing AI', exact: true }).click()
  await expect(task.getByText('4 task files saved together.')).toBeVisible()
  await task.getByRole('button', { name: 'Undo manuscript save' }).click()
  await page.getByRole('dialog', { name: 'Undo manuscript save?' }).getByRole('button', { name: 'Undo manuscript save' }).click()
  await expect(file('methods').getByLabel('Unsaved')).toBeVisible()
  await expect(file('main').getByLabel('Unsaved')).toBeVisible()
  await file('main').click()
  await expect(source).toContainText(draft)
  await file('methods').click()
  await expect(source).toContainText(testMethodEdit)
  await expect(source).not.toContainText(testMethodLine)
})

test('resumes the one-request workflow across interrupted batches and verification and archives once', async ({ page }) => {
  test.setTimeout(120_000)
  await installPaper(page)
  const reopen = () => page.getByRole('button', { name: 'Writing AI', exact: true }).click()
  const task = page.getByRole('region', { name: 'Manuscript task' })
  const next = page.getByRole('region', { name: 'Source change proposal' }).last()
  const review = page.getByRole('dialog', { name: 'Review manuscript task' })
  const submission = page.getByRole('region', { name: 'Submission task' })
  await page.getByRole('textbox', { name: 'Project source editor' }).press('Control+Home')
  await page.keyboard.insertText('% unrelated author draft\n')
  await page.getByRole('textbox', { name: 'Message Writing AI' }).fill(
    'Read data/sessions.csv, revise the four chapters, compile the manuscript, and prepare the submission named Workflow acceptance.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await task.getByRole('button', { name: 'Continue task' }).click()
  await expect(next.getByRole('button', { name: 'Apply to drafts' })).toBeVisible()
  const evidence = next.getByRole('region', { name: 'Evidence for proposed changes' })
  await expect(evidence.getByRole('button', { name: 'CSV · data/sessions.csv:2' })).toBeVisible()
  await expect(evidence.getByRole('listitem', { name: 'A follow-up measured 31.7 degrees.', exact: true })
    .getByText('Needs author confirmation')).toBeVisible()
  await page.reload()
  await reopen()
  await expect(task.getByRole('status')).toContainText('0 of 4 files applied')
  await next.getByRole('button', { name: 'Apply to drafts' }).click()
  await expect(task.getByRole('status')).toContainText('3 of 4 files applied')

  let ready!: () => void
  let release!: () => void
  const compiled = new Promise<void>(resolve => { ready = resolve })
  const proceed = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/latex/compile?*', async route => {
    const response = await route.fetch()
    ready()
    await proceed
    await route.fulfill({ response }).catch(() => {})
  }, { times: 1 })
  try {
    await next.getByRole('button', { name: 'Apply to drafts' }).click()
    await compiled
    await page.reload()
  } finally { release() }
  await reopen()
  await expect(task.getByRole('status')).toContainText('4 of 4 files applied')
  await task.getByRole('button', { name: 'Review and save task' }).click()
  await expect(review.getByRole('status')).toContainText('Manuscript verification passed.')
  const save = review.getByRole('button', { name: 'Save verified files' })
  await expect(save).toBeDisabled()
  await review.getByRole('button', { name: 'sections/results.tex', exact: true }).click()
  for (const claim of await review.getByRole('button', { name: 'Confirm claim' }).all()) await claim.click()
  await save.click()
  await expect(task.getByText('4 task files saved together.')).toBeVisible()
  await expect(page.getByRole('button', { name: /^main\.tex Main/ }).getByLabel('Unsaved')).toBeVisible()
  await expect(submission.getByText(/ZIP SHA-256/)).toBeVisible()
  await page.reload()
  await reopen()
  await expect(submission.getByRole('textbox', { name: 'Submission version name' })).toHaveValue('Workflow acceptance')
  await submission.getByRole('button', { name: 'Confirm submission archive' }).click()
  await expect(submission.getByText('Archived Workflow acceptance.')).toBeVisible()
  await page.reload()
  await reopen()
  await expect(submission).toHaveCount(1)
  await expect(submission.getByText('Archived Workflow acceptance.')).toBeVisible()
  await expect(submission.getByRole('button', { name: 'Confirm submission archive' })).toHaveCount(0)
})

test('reviews Morning Walk claims separately and reopens only the changed data dependency', async ({ page }) => {
  test.setTimeout(120_000)
  await page.goto('/research')
  await page.getByLabel('Choose project ZIP or backup').setInputFiles({
    name: 'Morning Walk Study.zip', mimeType: 'application/zip', buffer: await morningWalkZip(),
  })
  const openAi = () => page.getByRole('button', { name: 'Writing AI', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Morning Walk Study', level: 1 })).toBeVisible()
  await openAi()
  await page.getByRole('textbox', { name: 'Message Writing AI' }).fill(
    'Morning claim review. Read data/sessions.csv, revise Methods and Results, compile and prepare the submission.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  const task = page.getByRole('region', { name: 'Manuscript task' })
  const review = page.getByRole('dialog', { name: 'Review manuscript task' })
  const showResults = () => review.getByRole('button', { name: 'sections/results.tex', exact: true }).click()
  await task.getByRole('button', { name: 'Continue task' }).click()
  await page.getByRole('region', { name: 'Source change proposal' }).last().getByRole('button', { name: 'Apply to drafts' }).click()
  await showResults()
  const claim = (name: string) => review.getByRole('listitem', { name, exact: true })
  const direct = claim('The first recorded value was 28.1 degrees.')
  const mean = claim('The mean of the second and third sessions was 27.25 degrees.')
  const unsupported = claim('Follow-up sessions improved by 12.9 degrees.')
  await direct.getByRole('button', { name: 'Confirm claim' }).click()
  await page.route('**/api/latex/chat', route => route.abort('connectionreset'), { times: 1 })
  const interruptedEvidence = page.waitForRequest('**/api/latex/chat')
  await mean.getByRole('button', { name: 'Request evidence' }).click()
  const firstEvidence = (await interruptedEvidence).postDataJSON()
  const resumedEvidence = page.waitForRequest('**/api/latex/chat')
  await page.getByRole('button', { name: 'Retry request' }).click()
  const retryEvidence = (await resumedEvidence).postDataJSON()
  expect(retryEvidence).toMatchObject({ manuscript: { mode: 'evidence', claim: firstEvidence.manuscript.claim }, scope: [] })
  await showResults()
  const calculation = mean.getByRole('region', { name: 'CSV calculation calc-1' })
  await expect(calculation.getByText('(27.5 + 27) / 2 = 27.25 · 2 decimal places')).toBeVisible()
  await expect(calculation.getByRole('button', { name: 'data/sessions.csv:3' })).toBeVisible()
  await expect(calculation.getByRole('button', { name: 'data/sessions.csv:4' })).toBeVisible()
  await mean.getByRole('button', { name: 'Confirm claim' }).click()
  await unsupported.getByRole('button', { name: 'Exclude change' }).click()
  await expect(unsupported.getByText('Excluded from draft')).toBeVisible()
  await page.reload()
  await openAi()
  await task.getByRole('button', { name: 'Review and save task' }).click()
  await showResults()
  await expect(direct.getByText('Confirmed', { exact: true })).toBeVisible()
  await expect(mean.getByText('Confirmed', { exact: true })).toBeVisible()
  await expect(unsupported.getByText('Excluded from draft')).toBeVisible()
  await direct.getByRole('button', { name: 'CSV · data/sessions.csv:2' }).click()
  const editor = page.getByRole('textbox', { name: 'Project source editor' })
  const csvSource = page.getByRole('region', { name: 'Source editor' }).locator('.view-lines')
  await expect(csvSource).toContainText('1,28.1,30.7')
  await expect(editor).toBeFocused()
  await editor.press('Control+Home')
  await editor.press('ArrowDown')
  await editor.press('Home')
  await editor.press('Shift+End')
  await page.keyboard.insertText('1,28.2,30.7')
  await expect(csvSource).toContainText('1,28.2,30.7')
  await page.getByRole('button', { name: 'Back to manuscript review' }).click()
  await expect(direct.getByText('Evidence or wording changed. Review again.')).toBeVisible()
  const queue = review.getByRole('region', { name: 'Manuscript review queue' })
  const changed = queue.getByRole('button', { name: /Evidence or wording changed.*28\.1 degrees/ })
  await expect(changed).toHaveAttribute('aria-pressed', 'true')
  await expect(queue.getByRole('button', { name: /27\.25 degrees/ })).toHaveCount(0)
  await expect(mean.getByText('Confirmed', { exact: true })).toBeVisible()
  await expect(unsupported.getByText('Excluded from draft')).toBeVisible()
  await expect(review.getByRole('button', { name: 'Save verified files' })).toBeDisabled()
  await page.reload()
  await openAi()
  await task.getByRole('button', { name: 'Review and save task' }).click()
  await expect(changed).toHaveAttribute('aria-pressed', 'true')
  await expect(mean.getByText('Confirmed', { exact: true })).toBeVisible()
})
