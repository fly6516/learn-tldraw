import { expect, test, type Page } from '@playwright/test'
import JSZip from 'jszip'
import { testMethodEdit, testMethodLine, testResultEdit } from '../../src/lib/project/test-paper'

async function installPaper(page: Page) {
  await page.goto('/research')
  const response = await page.request.get('/api/latex/test-fixture')
  expect(response.ok()).toBe(true)
  const zip = await JSZip.loadAsync(await response.body())
  zip.file('notes/first.tex', 'Original test note.\n')
  zip.file('notes/second.tex', 'Original test note.\n')
  zip.file('data/sessions.csv', 'session,shade\n1,28.1\n2,27.5\n')
  await page.getByLabel('Choose project ZIP or backup').setInputFiles({
    name: 'Batch Paper.zip', mimeType: 'application/zip', buffer: await zip.generateAsync({ type: 'nodebuffer' }),
  })
  await expect(page.getByRole('heading', { name: 'Batch Paper', level: 1 })).toBeVisible()
  await page.getByRole('button', { name: 'Writing AI', exact: true }).click()
}

test('applies a manuscript in batches, undoes safely and resumes with retained decisions', async ({ page }) => {
  await installPaper(page)
  const composer = page.getByRole('textbox', { name: 'Message Writing AI' })
  await page.getByRole('combobox', { name: 'Approval mode' }).selectOption('full')
  await page.getByRole('button', { name: 'Grant full draft access', exact: true }).click()
  await composer.fill('Test: revise the complete manuscript in batches')
  await page.getByRole('button', { name: 'Plan writing task' }).click()
  const task = page.getByRole('region', { name: 'Manuscript task' })
  await expect(task.getByRole('status')).toContainText('0 of 4 files applied')
  await task.getByRole('button', { name: 'Continue task' }).click()
  await expect(task.getByRole('status')).toContainText('4 of 4 files applied')
  await expect(task.getByText('Batches · 2')).toBeVisible()

  await task.getByRole('button', { name: 'Undo latest batch' }).click()
  await page.getByRole('button', { name: 'Confirm undo' }).click()
  await expect(task.getByRole('status')).toContainText('3 of 4 files applied')
  await task.getByText('Author decisions and open questions').click()
  const decisions = task.getByRole('textbox', { name: 'Task author decisions' })
  await decisions.fill('Keep all data labeled synthetic.')
  await decisions.press('Tab')

  await page.getByRole('button', { name: /^methods\.tex/ }).click()
  const editor = page.getByRole('textbox', { name: 'Project source editor' })
  await editor.press('Control+End')
  await page.keyboard.insertText('\nAuthor follow-up stays here.')
  await task.getByRole('button', { name: 'Undo task batches' }).click()
  await page.getByRole('button', { name: 'Confirm undo' }).click()
  const conflict = page.getByRole('dialog', { name: 'Undo this batch?' })
  await expect(conflict.getByRole('alert')).toContainText('sections/methods.tex')
  await conflict.getByRole('button', { name: 'Cancel' }).click()
  const source = page.getByRole('region', { name: 'Source editor' }).locator('.view-lines')
  await expect(source).toContainText('Author follow-up stays here.')
  await expect(source).toContainText(testMethodEdit)

  const messages = page.locator('[aria-label="Conversation messages"]')
  const revisionReceipts = messages.getByText('There are no revision rounds in this project.', { exact: true })
  for (let count = 1; count <= 31; count++) {
    await composer.fill('/revisions')
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(revisionReceipts).toHaveCount(count)
  }
  await page.reload()
  await page.getByRole('button', { name: 'Writing AI', exact: true }).click()
  await expect(revisionReceipts).toHaveCount(30)
  await expect(task.getByRole('status')).toContainText('3 of 4 files applied')
  await task.getByText('Author decisions and open questions').click()
  await expect(decisions).toHaveValue('Keep all data labeled synthetic.')
  await expect(page.getByRole('combobox', { name: 'Approval mode' })).toHaveValue('manual')
  await task.getByRole('button', { name: 'Continue task' }).click()
  const latest = page.getByRole('region', { name: 'Source change proposal' }).last()
  await expect(latest.getByRole('button', { name: 'Apply to drafts' })).toBeVisible()
  await latest.getByRole('button', { name: 'Apply to drafts' }).click()
  await expect(task.getByRole('status')).toContainText('4 of 4 files applied')
})

