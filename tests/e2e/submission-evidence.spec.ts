import { expect, firefox, test } from '@playwright/test'
import JSZip from 'jszip'
import { readFile } from 'node:fs/promises'
import { morningWalkZip } from '../fixtures/morning-walk'

test('checks the final ZIP for missing and changed claim evidence and archives the exact exception', async ({ page, baseURL }, info) => {
  test.setTimeout(120_000)
  await page.goto('/research')
  await page.getByLabel('Choose project ZIP or backup').setInputFiles({
    name: 'Morning Walk Study.zip', mimeType: 'application/zip', buffer: await morningWalkZip(),
  })
  await page.getByRole('button', { name: 'Writing AI', exact: true }).click()
  await page.getByRole('textbox', { name: 'Message Writing AI' }).fill(
    'Morning claim review. Read data/sessions.csv, revise Methods and Results, compile and prepare the submission.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.getByRole('button', { name: 'Continue task' }).click()
  await page.getByRole('button', { name: 'Apply to drafts' }).last().click()
  const review = page.getByRole('dialog', { name: 'Review manuscript task' })
  await review.getByRole('button', { name: 'sections/results.tex', exact: true }).click()
  const claim = (quote: string) => review.getByRole('listitem', { name: quote, exact: true })
  const direct = 'The first recorded value was 28.1 degrees.'
  const mean = 'The mean of the second and third sessions was 27.25 degrees.'
  await claim(direct).getByRole('button', { name: 'Confirm claim' }).click()
  await claim(mean).getByRole('button', { name: 'Request evidence' }).click()
  await claim(mean).getByRole('button', { name: 'Confirm claim' }).click()
  await claim('Follow-up sessions improved by 12.9 degrees.').getByRole('button', { name: 'Exclude change' }).click()
  await expect(claim('Follow-up sessions improved by 12.9 degrees.')).toContainText('Excluded from draft')
  await review.getByRole('button', { name: 'Verify manuscript' }).click()
  await expect(review.getByRole('status')).toContainText('Manuscript verification passed.')
  await review.getByRole('button', { name: 'Save verified files' }).click()

  const chat = page.getByRole('region', { name: 'Submission task' })
  const evidence = (scope = chat) => scope.getByRole('region', { name: 'Submission evidence check' })
  await expect(evidence()).toContainText('2 saved claims checked · Final ZIP')
  await expect(evidence()).toContainText('No evidence differences found.')
  await chat.getByText('ZIP manifest', { exact: false }).click()
  const includeCsv = chat.getByRole('checkbox', { name: 'data/sessions.csv' })
  await includeCsv.uncheck()
  await expect(evidence()).toContainText('Evidence file is absent from this ZIP · data/sessions.csv')
  await expect(evidence()).toContainText(direct)
  await expect(evidence()).toContainText(mean)
  await includeCsv.check()
  await expect(evidence()).toContainText('No evidence differences found.')

  await page.getByRole('button', { name: 'Prepare submission', exact: true }).click()
  const submission = page.getByRole('dialog', { name: 'Prepare submission' })
  await submission.getByText('ZIP files', { exact: false }).click()
  await submission.getByRole('checkbox', { name: 'data/sessions.csv' }).uncheck()
  await evidence(submission).getByRole('button', { name: new RegExp('28\\.1 degrees') }).click()
  const editorRegion = page.getByRole('region', { name: 'Source editor' })
  const editor = editorRegion.getByRole('textbox', { name: 'Project source editor' })
  await expect(editorRegion.getByText('sections/results.tex', { exact: true })).toBeVisible()
  await expect(editor).toBeFocused()
  await editor.press('Home')
  await editor.press('Shift+End')
  await page.keyboard.insertText('% final submission edit')

  await page.getByRole('button', { name: 'Prepare submission', exact: true }).click()
  await submission.getByRole('radio', { name: 'Include local drafts in both downloads' }).check()
  await submission.getByText('ZIP files', { exact: false }).click()
  await expect(submission.getByRole('checkbox', { name: 'data/sessions.csv' })).not.toBeChecked()
  await submission.getByRole('button', { name: 'Compile submission files' }).click()
  const exception = submission.getByRole('checkbox', { name: 'Accept evidence exceptions for this ZIP' })
  await expect(exception).toBeVisible()
  await expect(evidence(submission)).toContainText('Reviewed wording is absent from this ZIP')
  await submission.getByRole('textbox', { name: 'Version name' }).fill('Evidence exception')
  const archive = submission.getByRole('button', { name: 'Save submission version' })
  await expect(archive).toBeDisabled()
  await exception.check()
  await archive.click()
  await submission.getByText(/^Evidence exception ·/).click()
  const archiveSection = submission.getByRole('region', { name: 'Archived submissions' })
  await archiveSection.getByText('Archived evidence check · 2 claims').click()
  await expect(archiveSection).toContainText('Evidence exceptions accepted for this ZIP.')
  const event = page.waitForEvent('download')
  await archiveSection.getByRole('button', { name: 'Download archived ZIP' }).click()
  const actual = await JSZip.loadAsync(await readFile(await (await event).path()))
  expect(actual.file('data/sessions.csv')).toBeNull()
  expect(await actual.file('sections/results.tex')!.async('string')).toContain('% final submission edit')
  expect(await actual.file('sections/results.tex')!.async('string')).not.toContain(direct)

  await page.reload()
  await page.getByRole('button', { name: 'Prepare submission', exact: true }).click()
  await submission.getByText(/^Evidence exception ·/).click()
  await archiveSection.getByText('Archived evidence check · 2 claims').click()
  await expect(archiveSection).toContainText('Evidence exceptions accepted for this ZIP.')

  await submission.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Project menu' }).click()
  await page.getByRole('menuitem', { name: 'Project Backup' }).click()
  await page.getByRole('checkbox', { name: 'Include submissions and revision rounds' }).check()
  const backupEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download Backup' }).click()
  const backup = info.outputPath('evidence.research-canvas')
  await (await backupEvent).saveAs(backup)
  const browser = await firefox.launch()
  try {
    const restored = await browser.newPage({ baseURL })
    await restored.goto('/research')
    await restored.getByLabel('Choose project ZIP or backup').setInputFiles(backup)
    await restored.getByRole('button', { name: 'Import as new project' }).click()
    await restored.getByRole('button', { name: 'Writing', exact: true }).click()
    await restored.getByRole('button', { name: 'Prepare submission', exact: true }).click()
    await restored.getByText(/^Evidence exception ·/).click()
    await restored.getByText('Archived evidence check · 2 claims').click()
    await expect(restored.getByText('Evidence exceptions accepted for this ZIP.')).toBeVisible()
  } finally {
    await browser.close()
  }
})
