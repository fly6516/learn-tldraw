import { expect, test } from '@playwright/test'
import { morningWalkZip } from '../fixtures/morning-walk'

test('previews and undoes bibliography merges and cross-file renames while keeping Morning Walk Study compilable', async ({ page }) => {
  test.setTimeout(120_000)
  await page.goto('/research')
  await page.getByLabel('Choose project ZIP or backup').setInputFiles({
    name: 'Morning Walk Study.zip', mimeType: 'application/zip', buffer: await morningWalkZip(),
  })
  const openFile = (path: string) => page.getByRole('complementary', { name: 'Project navigation' }).getByTitle(path, { exact: true }).click()
  const source = page.getByRole('region', { name: 'Source editor' }).locator('.view-lines')
  const editor = page.getByRole('textbox', { name: 'Project source editor' })
  const undo = page.getByRole('button', { name: 'Undo reference changes', exact: true })
  await openFile('sections/methods.tex')
  await editor.press('Control+Home')
  await page.keyboard.insertText('See section~\\ref{sec:results}.\n')
  await expect(page.getByText('1 local draft · Not saved to project')).toBeVisible()

  await page.getByRole('button', { name: 'Cross-references', exact: true }).click()
  await page.getByRole('button', { name: 'Rename LaTeX label sec:results', exact: true }).click()
  const labels = page.getByRole('dialog', { name: 'Rename LaTeX label' })
  await labels.getByRole('textbox', { name: 'New key' }).fill('sec:findings')
  await labels.getByRole('button', { name: 'Preview changes' }).click()
  await expect(labels.getByText(/sections\/methods\.tex:1 · local draft/)).toBeVisible()
  await expect(labels.getByText(/sections\/results\.tex:2 · saved source/)).toBeVisible()
  await expect(page.locator('[aria-label="Source editor"] .view-lines')).toContainText('\\ref{sec:results}')
  await labels.getByRole('button', { name: 'Apply reference changes' }).click()
  await expect(source).toContainText('\\ref{sec:findings}')
  await openFile('sections/results.tex')
  await expect(source).toContainText('\\label{sec:findings}')
  await undo.click()
  await openFile('sections/methods.tex')
  await expect(source).toContainText('\\ref{sec:results}')

  await page.getByRole('button', { name: 'References', exact: true }).click()
  await page.getByRole('button', { name: 'Merge bibliography', exact: true }).click()
  const merge = page.getByRole('dialog', { name: 'Merge bibliography' })
  await merge.getByLabel('Bibliography file to import').setInputFiles({
    name: 'new-references.bib', mimeType: 'text/plain',
    buffer: Buffer.from('@book{oke2017,title={Keep the existing entry}}\n@book{trial2026,title={Additional Reading},year={2026}}'),
  })
  await merge.getByRole('button', { name: 'Preview changes' }).click()
  await expect(merge.getByText(/Entries to add.*trial2026/)).toBeVisible()
  await expect(merge.getByText(/Existing keys kept.*oke2017/)).toBeVisible()
  await merge.getByRole('button', { name: 'Apply reference changes' }).click()
  await expect(page.getByRole('region', { name: 'References', exact: true }).getByText('Additional Reading')).toBeVisible()
  await undo.click()
  await expect(page.getByRole('region', { name: 'References', exact: true }).getByText('Additional Reading')).toHaveCount(0)

  const references = page.getByRole('region', { name: 'References', exact: true })
  await references.getByLabel('Search bibliography').fill('oke2017')
  await references.getByRole('button', { name: 'Add to Canvas' }).click()
  await page.getByRole('dialog', { name: 'Add to Canvas' }).getByRole('button', { name: 'Add card' }).click()
  await expect(page.getByRole('button', { name: 'Canvas', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.getByRole('button', { name: 'Writing', exact: true }).click()
  await references.getByRole('button', { name: 'Rename citation key oke2017' }).click()
  const citations = page.getByRole('dialog', { name: 'Rename citation key' })
  await citations.getByRole('textbox', { name: 'New key' }).fill('oke2017-revised')
  await citations.getByRole('button', { name: 'Preview changes' }).click()
  await expect(citations.getByText(/sections\/calibration\.tex:5 · saved source/)).toBeVisible()
  await expect(citations.getByText(/references\/printed\.tex:.* · saved source/)).toBeVisible()
  await expect(citations.getByText('Canvas and review bindings (1)')).toBeVisible()
  await citations.getByRole('button', { name: 'Apply reference changes' }).click()
  await page.getByRole('button', { name: 'Compile PDF', exact: true }).click()
  await expect(page.getByText(/Last successful compile.*Up to date/)).toBeVisible()
  await references.getByRole('button', { name: /^oke2017-revised ·/ }).click()
  await expect(source).toContainText('oke2017-revised')
  await references.getByRole('button', { name: 'Locate on Canvas' }).click()
  await expect(page.getByText(/^oke2017-revised · references\/library\.bib:/).first()).toBeVisible()
  await page.getByRole('button', { name: 'Writing', exact: true }).click()
  await undo.click()
  await openFile('sections/calibration.tex')
  await expect(source).toContainText('\\cite{oke2017}')
  await openFile('sections/methods.tex')
  await expect(source).toContainText('\\ref{sec:results}')
  await page.getByRole('button', { name: 'Compile PDF', exact: true }).click()
  await expect(page.getByText(/Last successful compile.*Up to date/)).toBeVisible()
})
