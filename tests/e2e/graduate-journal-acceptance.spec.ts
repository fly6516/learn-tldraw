import { expect, test, type Page } from '@playwright/test'
import { join } from 'node:path'
import { readFile } from 'node:fs/promises'
import JSZip from 'jszip'
import { templateCatalog } from '../../src/lib/project/template-catalog'
import { archiveSubmission, compileProject, confirmTemplatePublication, loadCandidate, openLayoutReport, publisherFile,
  replaceProjectSource, reviewArchive, saveCompiledPdf, templateCard, useOfficialTemplate } from './support/official-template'

const fixtures = process.env.RESEARCH_GRADUATE_JOURNAL_FIXTURES
const ustcId = 'ustc-graduate-word'
const mnrasId = 'mnras'
const ustc = templateCatalog.find(entry => entry.id === ustcId)!
const mnras = templateCatalog.find(entry => entry.id === mnrasId)!
if (ustc.workflow.kind !== 'word' || mnras.delivery !== 'archive') throw new Error('Acceptance catalog entries are missing.')
const ustcOrigin = { ...ustc.workflow.original, version: ustc.workflow.version }
const version = 'qa-2026.1'

function forTemplate(page: Page, category: 'school' | 'journal', id: string) {
  return page.goto(templateCard(category, id) + '&manage=1')
}

async function assertPublisherSource(page: Page) {
  const details = page.getByRole('complementary', { name: 'Template details' })
  await details.getByRole('button', { name: '检查官方原件更新' }).click()
  await expect(details.getByRole('status')).toContainText('所检查的官方原件与当前发布版一致。', { timeout: 25_000 })
  await expect(details.getByText('待人工核对', { exact: true })).toBeVisible()
}

async function acceptWord(page: Page, update = false) {
  const builder = page.getByRole('dialog', { name: update ? '验收模板候选' : '从 Word 生成模板' })
  if (update) await builder.getByLabel('候选版本号').fill(version)
  await expect(builder.getByText('已校验官方 Word', { exact: false })).toBeVisible()
  await expect(builder.getByLabel('Word 样例')).toHaveCount(0)
  await builder.getByRole('button', { name: '生成版式配置' }).click()
  await expect(builder.getByLabel('纸张')).toHaveValue('a4', { timeout: 30_000 })
  const conflicts = builder.getByText('样例与规范不一致，请选择').locator('..')
  while (await conflicts.count()) await conflicts.first().getByRole('button', { name: '采用规范' }).click()
  await expect(builder.getByLabel('正文首页排版')).toHaveValue('odd')
  await expect(builder.getByLabel('摘要与目录页码')).toHaveValue('Roman')
  await expect(builder.getByLabel('页眉内容规则')).toHaveValue('chapter-all')
  await expect(builder.getByLabel('页眉位置')).toHaveValue('center')
  await builder.getByLabel('目录层级（0 关闭）').fill('2')
  await builder.getByLabel('页码位置').selectOption('center')
  await builder.getByLabel('参考文献', { exact: true }).selectOption('numbered')
  await builder.getByLabel('模板名称').fill(update ? '中科大换版样例' : '中科大官方版式验收')
  if (update) await expect(builder.getByLabel('左边距（mm）')).toHaveValue('35')
  const save = builder.getByRole('button', { name: update ? '发布新版本' : '保存到我的模板' })
  await expect(save).toBeDisabled()
  const request = page.waitForResponse(res => res.url().includes('/api/latex/compile?'), { timeout: 130_000 })
  await builder.getByRole('button', { name: '编译 PDF 预览' }).click()
  const response = await request
  expect(response.ok(), response.ok() ? undefined : (await response.text()).slice(0, 1500)).toBe(true)
  await expect(builder.getByRole('link', { name: '下载预览 PDF' })).toBeVisible({ timeout: 60_000 })
  await save.click()
  if (update) await confirmTemplatePublication(page, version, ustcOrigin.version)
  await expect(builder).toBeHidden()
}

async function loadWord(page: Page, name: string) {
  const importer = page.getByRole('dialog', { name: 'Import Word to TeX' })
  await importer.getByLabel('Project name').fill(name)
  await importer.getByLabel('Word manuscript').setInputFiles(join(fixtures!, 'ustc-manuscript.docx'))
  const request = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/word/import'))
  await importer.getByRole('button', { name: 'Create TeX project' }).click()
  const response = await request
  expect(response.ok(), response.ok() ? undefined : await response.text()).toBe(true)
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  return JSZip.loadAsync(await response.body())
}

test('USTC official Word acceptance from source, independent manuscript, even body opening, and retained release', async ({ page }, info) => {
  test.skip(!fixtures, 'See docs/official-template-acceptance.md for the publisher files and fixture setup.')
  test.setTimeout(240_000)
  const original = await publisherFile(join(fixtures!, 'ustc-2026-11.docx'), ustcOrigin.sha256)
  await forTemplate(page, 'school', ustcId)
  await assertPublisherSource(page)
  await useOfficialTemplate(page, ustcOrigin.sha256)
  await acceptWord(page)
  await page.getByRole('button', { name: '使用模板', exact: true }).click()
  const project = await loadWord(page, '中科大独立稿验收')
  await page.waitForURL(url => url.searchParams.has('project'))
  const oldUrl = page.url()
  const independent = await project.file('manuscript.tex')!.async('string')
  expect(independent).toContain('校园无障碍路径观察')
  expect(independent).toContain('表 1.1 模拟记录表')
  expect(independent).not.toContain('中国科学技术大学学位论文原创性声明')
  const main = await project.file('main.tex')!.async('string')
  const layoutSource = await project.file('word-layout.tex')!.async('string')
  const wrong = layoutSource.replace(String.raw`\ifodd\ReadonlyShipoutCounter\relax`, String.raw`\iffalse`)
  expect(wrong).not.toBe(layoutSource)
  await compileProject(page)
  for (const number of [2, 3, 4, 5]) {
    await page.getByRole('button', { name: 'Next PDF page' }).click()
    const current = page.getByRole('region', { name: 'Compiled PDF, page ' + number, exact: true })
    await expect(current).toContainText(number === 4 ? /^\s*IV\s*$/ : /\S/)
  }
  const bodyPage = page.getByRole('region', { name: 'Compiled PDF, page 5', exact: true })
  await expect(bodyPage).toContainText(/校园无障碍路径观察[\s\S]*校园无障碍路径观察/)
  await expect(bodyPage).not.toContainText('本科毕业设计')
  await saveCompiledPdf(page, info.outputPath('ustc-independent.pdf'))
  let report = await openLayoutReport(page)
  const row = (label: string) => report.getByRole('listitem').filter({ hasText: label })
  await expect(row('正文奇数页起排')).toContainText('已核对')
  await expect(row('正文奇数页起排')).toContainText('第 5 页')
  await expect(row('前置连续页码')).toContainText('I、II、III、IV')
  await expect(row('前置连续页码')).toContainText('已核对')
  await expect(row('正文起始页码')).toContainText('已核对')
  await expect(row('目录页码')).toContainText('已核对')
  await expect(row('参考文献缺项')).toContainText('已核对')
  await report.getByRole('button', { name: 'Close' }).click()

  await replaceProjectSource(page, 'word-layout.tex', wrong)
  await compileProject(page)
  report = await openLayoutReport(page)
  await expect(row('正文奇数页起排')).toContainText('发现问题')
  await expect(row('正文奇数页起排')).toContainText('第 4 页')
  await row('正文奇数页起排').getByRole('button', { name: /word-layout\.tex:\d+/ }).click()
  await expect(report).toBeHidden()
  await replaceProjectSource(page, 'word-layout.tex', layoutSource)
  await compileProject(page)
  report = await openLayoutReport(page)
  await expect(row('正文奇数页起排')).toContainText('已核对')
  await report.getByRole('button', { name: 'Close' }).click()
  await archiveSubmission(page, '中科大初始版报告', '其余版式规范')

  const candidate = await JSZip.loadAsync(original)
  const xml = await candidate.file('word/document.xml')!.async('string')
  candidate.file('word/document.xml', xml.replace(/(<w:pgMar\b[^>]*\bw:left=")\d+/g, (_match, prefix: string) => prefix + '1984'))
  await forTemplate(page, 'school', ustcId)
  await loadCandidate(page, ustcId, ustc.sourceUrl!, ustcOrigin.version, 'ustc-qa.docx', await candidate.generateAsync({ type: 'nodebuffer' }))
  await acceptWord(page, true)
  await expect(page.getByText('当前发布版 ' + version, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '使用模板', exact: true }).click()
  const updated = await loadWord(page, '中科大新版本稿件')
  expect(await updated.file('main.tex')!.async('string')).toContain('left=35mm')
  await compileProject(page)
  await reviewArchive(page, oldUrl, '中科大初始版报告', ustcId + ' · ' + ustcOrigin.version, async report => {
    await expect(report).toContainText('正文奇数页起排')
    await expect(report).toContainText('前置连续页码')
  })
  await compileProject(page)
  const oldReport = await openLayoutReport(page)
  const oldMargin = /\bleft=(\d+(?:\.\d+)?)mm/.exec(main)![1]
  const oldMarginRow = oldReport.getByRole('listitem').filter({ hasText: '正文页边距' })
  await expect(oldMarginRow).toContainText('已核对')
  await expect(oldMarginRow).toContainText('左 ' + oldMargin + ' mm')
  await expect(oldMarginRow).not.toContainText('左 35 mm')
})

test('MNRAS official ZIP acceptance from source, independent manuscript, single-column body, and retained release', async ({ page }, info) => {
  test.skip(!fixtures, 'See docs/official-template-acceptance.md for the publisher files and fixture setup.')
  test.setTimeout(180_000)
  const original = await publisherFile(join(fixtures!, 'mnras.zip'), mnras.template.sha256)
  const main = mnras.template.mainFile
  const manuscript = await readFile(join('tests', 'e2e', 'fixtures', 'official-template-acceptance', 'mnras-manuscript.tex'), 'utf8')
  const wrong = manuscript.replace('usenatbib]', 'usenatbib,onecolumn]')
  expect(wrong).not.toBe(manuscript)
  await forTemplate(page, 'journal', mnrasId)
  await assertPublisherSource(page)
  await useOfficialTemplate(page, mnras.template.sha256)
  const create = page.getByRole('dialog', { name: 'Create project from template' })
  await create.getByLabel('Project name').fill('MNRAS 初始版验收')
  await expect(create.getByText('已校验官方 ZIP', { exact: false })).toBeVisible()
  await expect(create.getByLabel('Publisher template ZIP')).toHaveCount(0)
  await create.getByRole('button', { name: 'Create project' }).click()
  await expect(page.getByRole('heading', { name: 'MNRAS 初始版验收', exact: true })).toBeVisible()
  await page.waitForURL(url => url.searchParams.has('project'))
  const oldUrl = page.url()
  await compileProject(page)
  await replaceProjectSource(page, main, manuscript.replace('{graphicx}', '{graphicx,researchqa-notinstalled}'))
  const failedBuild = page.waitForResponse(response => response.url().includes('/api/latex/compile?') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Compile PDF', exact: true }).click()
  const failure = await failedBuild
  expect(failure.status()).toBe(422)
  expect((await failure.json()).error).toContain('缺少 LaTeX 依赖文件 researchqa-notinstalled.sty')
  await replaceProjectSource(page, main, manuscript)
  await compileProject(page)
  await expect(page.getByRole('region', { name: 'Compiled PDF, page 1', exact: true })).toContainText('Repeatable Survey Window Checks')
  await saveCompiledPdf(page, info.outputPath('mnras-independent.pdf'))
  let report = await openLayoutReport(page)
  const classRow = () => report.getByRole('listitem').filter({ hasText: 'MNRAS 正文双栏' })
  await expect(classRow()).toContainText('已核对')
  await expect(classRow()).toContainText('PDF 正文两列文字')
  await expect(report.getByRole('listitem').filter({ hasText: 'MNRAS 图表显示' })).toContainText('已核对')
  await expect(report.getByRole('listitem').filter({ hasText: '参考文献缺项' })).toContainText('已核对')
  await report.getByRole('button', { name: 'Close' }).click()
  await replaceProjectSource(page, main, wrong)
  await compileProject(page)
  report = await openLayoutReport(page)
  await expect(classRow()).toContainText('发现问题')
  await expect(classRow()).toContainText('onecolumn')
  await classRow().getByRole('button', { name: /mnras_template\.tex:1/ }).click()
  await expect(report).toBeHidden()
  await replaceProjectSource(page, main, manuscript)
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('All changes saved to project')).toBeVisible()
  await compileProject(page)
  report = await openLayoutReport(page)
  await expect(classRow()).toContainText('已核对')
  await expect(classRow()).toContainText('PDF 正文两列文字')
  await expect(report.getByRole('listitem').filter({ hasText: 'MNRAS 图表显示' })).toContainText('已核对')
  await report.getByRole('button', { name: 'Close' }).click()
  await archiveSubmission(page, 'MNRAS 初始版报告', 'MNRAS 投稿细则')

  const candidate = await JSZip.loadAsync(original)
  candidate.file(main, manuscript.replace('Repeatable Survey Window Checks', 'Candidate Survey Window Checks'))
  await forTemplate(page, 'journal', mnrasId)
  await loadCandidate(page, mnrasId, mnras.sourceUrl!, mnras.template.version, 'mnras-qa.zip', await candidate.generateAsync({ type: 'nodebuffer' }))
  const verify = page.getByRole('dialog', { name: '验收模板候选' })
  await verify.getByLabel('候选版本号').fill(version)
  await expect(verify.getByText('已校验官方 ZIP', { exact: false })).toBeVisible()
  await expect(verify.getByLabel('候选官方 ZIP')).toHaveCount(0)
  await expect(verify.getByRole('button', { name: '发布新版本' })).toHaveCount(0)
  await verify.getByRole('button', { name: '编译候选' }).click()
  await expect(verify.getByRole('link', { name: '查看候选 PDF' })).toBeVisible({ timeout: 60_000 })
  await verify.getByRole('button', { name: '发布新版本' }).click()
  await confirmTemplatePublication(page, version, mnras.template.version)
  await expect(verify).toBeHidden()
  await expect(page.getByText('当前发布版 ' + version, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '使用模板', exact: true }).click()
  await create.getByLabel('Project name').fill('MNRAS 新版本验收')
  await create.getByRole('button', { name: 'Create project' }).click()
  await page.waitForURL(url => url.searchParams.has('project'))
  await expect(page.getByRole('heading', { name: 'MNRAS 新版本验收', exact: true })).toBeVisible()
  await compileProject(page)
  const pageOne = page.getByRole('region', { name: 'Compiled PDF, page 1', exact: true })
  await expect(pageOne).toContainText('Candidate Survey Window Checks')

  await reviewArchive(page, oldUrl, 'MNRAS 初始版报告', mnrasId + ' · ' + mnras.template.version, async report => {
    await expect(report).toContainText('MNRAS 正文双栏')
    await expect(report).toContainText('MNRAS 图表显示')
  })
  await compileProject(page)
  await expect(pageOne).toContainText('Repeatable Survey Window Checks')
})

test('reports official source hash and availability errors and keeps manual ZIP import available', async ({ page, request, baseURL }) => {
  test.skip(!fixtures, 'Requires the MNRAS publisher archive.')
  const source = '/api/templates/source?id=' + mnrasId + '&sha256='
  const wrongHash = await request.post(source + 'a'.repeat(64), { headers: { Origin: baseURL! }, timeout: 30_000 })
  expect(wrongHash.status()).toBe(409)
  expect(await wrongHash.json()).toMatchObject({ error: expect.stringContaining('SHA-256 校验失败') })

  await page.route(url => url.pathname === '/api/templates/source' && url.searchParams.has('sha256'),
    route => route.fulfill({ status: 502, json: { error: '官方站点暂时无法读取。' } }))
  await forTemplate(page, 'journal', mnrasId)
  await page.getByRole('button', { name: '使用模板', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Template catalog' }).getByRole('alert')).toContainText('官方站点暂时无法读取')
  await page.getByRole('button', { name: '手动上传原件', exact: true }).click()
  const create = page.getByRole('dialog', { name: 'Create project from template' })
  await create.getByLabel('Project name').fill('MNRAS 手动导入验收')
  await create.getByLabel('Publisher template ZIP').setInputFiles(join(fixtures!, 'mnras.zip'))
  await create.getByRole('button', { name: 'Create project' }).click()
  await expect(page.getByRole('heading', { name: 'MNRAS 手动导入验收', exact: true })).toBeVisible()
  await compileProject(page)
})
