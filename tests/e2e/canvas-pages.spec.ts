import { expect, test } from '@playwright/test'

test('deletes a Canvas page with its cards, supports undo and redo, and protects the last page', async ({ page }) => {
  await page.goto('/research-test')
  const explorer = page.getByRole('navigation', { name: 'Canvas pages' })
  await expect(explorer.getByRole('button', { name: /^Delete page/ })).toHaveCount(1)
  await expect(explorer.getByRole('button', { name: /^Delete page/ })).toBeDisabled()
  await explorer.getByRole('button', { name: 'Add Page' }).click()
  await explorer.getByRole('button', { name: /^Page 2\b/ }).click()
  await page.getByRole('button', { name: 'Add node' }).click()
  await page.getByRole('menuitem', { name: 'Section', exact: true }).click()
  const remove = explorer.getByRole('button', { name: 'Delete page Page 2' })
  await remove.click()
  const confirmation = page.getByRole('dialog', { name: 'Delete Page 2?' })
  await expect(confirmation.getByText(/^This removes 1 card/)).toBeVisible()
  await confirmation.getByRole('button', { name: 'Cancel' }).click()
  await expect(remove).toBeVisible()
  await remove.click()
  await confirmation.getByRole('button', { name: 'Delete page', exact: true }).click()
  await expect(remove).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(explorer.getByRole('button', { name: /Page 2 1/ })).toBeVisible()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(remove).toHaveCount(0)
  await page.reload()
  await expect(explorer.getByRole('button', { name: /^Delete page/ })).toBeDisabled()
  await page.getByRole('button', { name: 'Writing', exact: true }).click()
  await expect(page.getByRole('button', { name: 'methods.tex', exact: true })).toBeVisible()
})
