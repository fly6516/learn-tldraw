import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { expect, test } from '@playwright/test'
import JSZip from 'jszip'

const fixture = process.env.RESEARCH_CUSTOM_WORD_FIXTURE_DIR

test('builds and reuses a template for a university outside the catalog', async ({ page }, info) => {
  test.skip(!fixture, 'Set RESEARCH_CUSTOM_WORD_FIXTURE_DIR to the directory with the SCAU sample, guidelines and independent manuscript.')
  test.setTimeout(150_000)
  await page.goto('/research?section=templates&category=mine')
  await page.getByRole('button', { name: '从 Word 生成模板' }).click()
  const builder = page.getByRole('dialog', { name: '从 Word 生成模板' })
  await builder.getByLabel('Word 样例').setInputFiles(join(fixture!, 'official.doc'))
  await builder.getByLabel('学校撰写规范（选填）').setInputFiles(join(fixture!, 'requirements.pdf'))
  await builder.getByLabel('使用 AI 辅助识别结构').check()
  await builder.getByRole('button', { name: '生成版式配置' }).click()
  await expect(builder.getByText(/AI (?:已完成|未配置|暂不可用)/)).toBeVisible({ timeout: 45_000 })
  await expect(builder.getByLabel('左边距（mm）')).toHaveValue('24')
  await expect(builder.getByLabel('装订线（mm）')).toHaveValue('5')
  await expect(builder.getByLabel('参考文献', { exact: true })).toHaveValue('author-year')
  await expect(builder.getByLabel('插图编号')).toHaveValue('continuous')
  await expect(builder.getByLabel('表格编号')).toHaveValue('continuous')
  await builder.getByLabel('模板名称').fill('华南农业大学 · 本科验收')
  // Exercise editing, while keeping the official sample’s original header and body margins.
  await builder.getByLabel('二级标题字号（pt）').fill('13')
  const conflict = builder.getByText('样例与规范不一致，请选择').locator('..')
  while (await conflict.count()) await conflict.first().getByRole('button', { name: '采用规范' }).click()
  const save = builder.getByRole('button', { name: '保存到我的模板' })
  await expect(save).toBeDisabled()
  await builder.getByRole('button', { name: '编译 PDF 预览' }).click()
  const preview = builder.getByRole('link', { name: '下载预览 PDF' })
  await expect(preview.or(builder.getByRole('alert'))).toBeVisible({ timeout: 60_000 })
  await expect(builder.getByRole('alert')).toHaveCount(0)
  const sampleDownload = page.waitForEvent('download')
  await preview.click()
  await (await sampleDownload).saveAs(info.outputPath('scau-layout-preview.pdf'))
  await save.click()
  await expect(builder).toBeHidden()
  await page.reload()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download ZIP' }).click()
  const archive = await JSZip.loadAsync(await readFile((await (await download).path())!))
  expect(Object.keys(archive.files).sort()).toEqual(['layout.json', 'template.json'])
  const rules = JSON.parse(await archive.file('layout.json')!.async('string')).rules
  expect(rules.heading2).toMatchObject({ decision: 'manual', chosen: { origin: 'user', value: 13 } })

  await page.getByRole('button', { name: '使用模板', exact: true }).click()
  const importer = page.getByRole('dialog', { name: 'Import Word to TeX' })
  await importer.getByLabel('Project name').fill('华南农业大学 · 河涌公共空间观测')
  const manuscriptPath = join(fixture!, 'manuscript.docx')
  await importer.getByLabel('Word manuscript').setInputFiles(manuscriptPath)
  const created = page.waitForResponse(response => response.url().endsWith('/api/word/import') && response.request().method() === 'POST')
  await importer.getByRole('button', { name: 'Create TeX project' }).click()
  const response = await created
  expect(response.ok(), response.ok() ? undefined : await response.text()).toBe(true)
  const zip = await JSZip.loadAsync(await response.body())
  const source = await zip.file('manuscript.tex')!.async('string')
  const head = await zip.file('main.tex')!.async('string')
  const layout = await zip.file('word-layout.tex')!.async('string')
  expect(head).toContain('top=24mm,bottom=24mm,left=24mm,right=24mm,bindingoffset=5mm')
  expect(source).toContain('河涌公共空间观测验收稿')
  expect(source).not.toContain('原创性声明')
  expect(source).not.toContain('正文文字')
  expect(source).toMatch(/\\subsubsection.*1\.1\.1 数据记录/)
  expect(source).toContain('\\caption{图 1 河涌断面示意}')
  expect(source).toContain('\\caption{表 1 两次样本计数}')
  expect(source).toMatch(/\\CustomWordReference{}\{?Jacobs/)
  expect(layout).toContain('\\fancyfoot[C]')
  expect(await zip.file('word-original/body.docx')!.async('nodebuffer')).toEqual(await readFile(manuscriptPath))
  await expect(page.getByRole('heading', { name: '华南农业大学 · 河涌公共空间观测' })).toBeVisible()
  await page.getByRole('button', { name: 'Compile PDF', exact: true }).click()
  const pdf = page.getByRole('region', { name: 'PDF Preview' })
  await expect(pdf.getByRole('link', { name: 'Download PDF' })).toBeVisible({ timeout: 60_000 })
  const nextPage = pdf.getByRole('button', { name: 'Next PDF page' })
  for (let number = 2; number <= 6; number++) {
    await nextPage.click()
    const sheet = page.getByRole('region', { name: 'Compiled PDF, page ' + number, exact: true })
    await expect(sheet).toBeVisible()
    if (number === 3) await expect(sheet).toContainText('1.1.1 数据记录')
    if (number === 4) {
      await expect(sheet).toContainText('河涌断面示意')
      await expect(sheet).toContainText('两次样本计数')
    }
    if (number === 6) await expect(sheet).toContainText('The Death and Life of Great American Cities')
  }
  const pdfDownload = page.waitForEvent('download')
  await pdf.getByRole('link', { name: 'Download PDF' }).click()
  await (await pdfDownload).saveAs(info.outputPath('scau-independent-manuscript.pdf'))
})

test('reopens, versions and restores a Word layout in a clean browser', async ({ browser, page }, info) => {
  test.skip(!fixture, 'Set RESEARCH_CUSTOM_WORD_FIXTURE_DIR to the directory with the SCAU sample and independent manuscripts.')
  test.setTimeout(150_000)
  const sample = join(fixture!, 'official.doc')
  const third = join(fixture!, 'third-manuscript.docx')
  const market = '/research?section=templates&category=mine'
  const name = '可迁移参考版式'
  await page.goto(market)
  await page.getByRole('button', { name: '从 Word 生成模板' }).click()
  const builder = page.getByRole('dialog')
  await builder.getByLabel('Word 样例').setInputFiles(sample)
  await builder.getByRole('button', { name: '生成版式配置' }).click()
  await builder.getByLabel('模板名称').fill(name)
  await builder.getByRole('button', { name: '编译 PDF 预览' }).click()
  await builder.getByRole('link', { name: '下载预览 PDF' }).waitFor({ timeout: 60_000 })
  await builder.getByRole('button', { name: '保存到我的模板' }).click()

  const create = async (target: typeof page, manuscript: string, project: string) => {
    await target.getByRole('button', { name: '使用模板', exact: true }).click()
    const dialog = target.getByRole('dialog', { name: 'Import Word to TeX' })
    await dialog.getByLabel('Project name').fill(project)
    await dialog.getByLabel('Word manuscript').setInputFiles(manuscript)
    const request = target.waitForResponse(response => response.url().endsWith('/api/word/import') && response.request().method() === 'POST')
    await dialog.getByRole('button', { name: 'Create TeX project' }).click()
    const response = await request
    expect(response.ok(), response.ok() ? undefined : await response.text()).toBe(true)
    await expect(target.getByRole('heading', { name: project })).toBeVisible()
    return JSZip.loadAsync(await response.body())
  }

  const old = await create(page, join(fixture!, 'manuscript.docx'), '旧版项目')
  const oldUrl = page.url()
  const original = JSON.parse(await old.file('layout.json')!.async('string'))
  expect(original.rules.left.chosen.value).toBe(24)
  await page.goto(market)
  await page.getByRole('button', { name: '编辑版式', exact: true }).click()
  const editing = page.getByRole('dialog', { name: '编辑 Word 版式' })
  await editing.getByLabel('模板名称').fill(name + '新版')
  await editing.getByLabel('左边距（mm）').fill('32')
  await editing.getByLabel('左边距（mm）').locator('../..').getByLabel('人工确认采用此规则').check()
  await editing.getByLabel('用于预览的 Word 稿件').setInputFiles(third)
  await editing.getByRole('button', { name: '编译 PDF 预览' }).click()
  await editing.getByRole('link', { name: '下载预览 PDF' }).waitFor({ timeout: 60_000 })
  await editing.getByRole('button', { name: '另存为新版本' }).click()
  await page.getByRole('button', { name: '查看版式规则' }).click()
  const review = page.getByRole('dialog', { name: '版式规则' })
  await expect(review).toContainText('1.0.1')
  await expect(review).toContainText('人工确认采用')
  await review.getByRole('button', { name: 'Close' }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download ZIP' }).click()
  const archive = info.outputPath('portable-layout.zip')
  await (await download).saveAs(archive)
  const clean = await browser.newPage({ baseURL: info.project.use.baseURL })
  try {
    await clean.goto(market)
    await clean.getByLabel('Choose template ZIP').setInputFiles(archive)
    await expect(clean.getByText('Word 版式已导入。')).toBeVisible()
    const restored = await create(clean, third, '第三份独立稿件')
    const rules = JSON.parse(await restored.file('layout.json')!.async('string'))
    expect(rules.rules.left).toMatchObject({ confirmed: true, chosen: { value: 32, origin: 'user' } })
    const source = await restored.file('manuscript.tex')!.async('string')
    expect(source).toContain('第三份独立稿件')
    expect(source).not.toContain('正文文字')
    expect(source).not.toContain('河涌公共空间观测验收稿')
    await clean.getByRole('button', { name: 'Compile PDF', exact: true }).click()
    await expect(clean.getByRole('link', { name: 'Download PDF' })).toBeVisible({ timeout: 60_000 })
    await clean.getByRole('button', { name: '版式核对' }).click()
    await expect(clean.getByRole('dialog', { name: '版式核对' })).toContainText('32 · 手动设置 · 人工确认采用')
  } finally { await clean.close() }
  await page.goto(oldUrl)
  await page.getByRole('button', { name: '版式核对' }).click()
  await expect(page.getByRole('dialog', { name: '版式核对' })).toContainText('24 · 从文件读取')
})

test('blocks preview until a guideline conflict is resolved', async ({ page }, info) => {
  test.skip(!fixture, 'Set RESEARCH_CUSTOM_WORD_FIXTURE_DIR to the directory with an independent Word manuscript.')
  await page.goto('/research?section=templates&category=mine')
  await page.getByRole('button', { name: '从 Word 生成模板' }).click()
  const builder = page.getByRole('dialog', { name: '从 Word 生成模板' })
  await builder.getByLabel('Word 样例').setInputFiles(join(fixture!, 'manuscript.docx'))
  await builder.getByLabel('学校撰写规范（选填）').setInputFiles({
    name: 'conflicting-rule.txt', mimeType: 'text/plain', buffer: Buffer.from('页边距 左 3.6cm'),
  })
  await builder.getByRole('button', { name: '生成版式配置' }).click()
  const row = builder.getByText('样例与规范不一致，请选择').locator('..')
  await expect(row).toBeVisible()
  const compile = builder.getByRole('button', { name: '编译 PDF 预览' })
  await expect(compile).toBeDisabled()
  await row.getByRole('button', { name: '采用规范' }).click()
  await expect(compile).toBeEnabled()
  await expect(builder.getByLabel('左边距（mm）')).toHaveValue('36')
  await compile.click()
  const preview = builder.getByRole('link', { name: '下载预览 PDF' })
  await expect(preview.or(builder.getByRole('alert'))).toBeVisible({ timeout: 60_000 })
  await expect(builder.getByRole('alert')).toHaveCount(0)
  const download = page.waitForEvent('download')
  await preview.click()
  await (await download).saveAs(info.outputPath('resolved-conflict.pdf'))
})

const graduateFixture = process.env.RESEARCH_GRADUATE_WORD_FIXTURE_DIR

test('renders Roman front matter and graduate running headers from an official Word layout', async ({ page }, info) => {
  test.skip(!graduateFixture, 'Set RESEARCH_GRADUATE_WORD_FIXTURE_DIR to the official NJUPT files and test manuscript.')
  test.setTimeout(150_000)
  await page.goto('/research?section=templates&category=mine')
  await page.getByRole('button', { name: '从 Word 生成模板' }).click()
  const builder = page.getByRole('dialog', { name: '从 Word 生成模板' })
  await builder.getByLabel('Word 样例').setInputFiles(join(graduateFixture!, 'official.doc'))
  await builder.getByLabel('学校撰写规范（选填）').setInputFiles(join(graduateFixture!, 'requirements.pdf'))
  await builder.getByRole('button', { name: '生成版式配置' }).click()
  await expect(builder.getByLabel('摘要与目录页码')).toHaveValue('Roman')
  await expect(builder.getByLabel('正文单双页页眉')).toHaveValue('split')
  await expect(builder.getByLabel('图表章号分隔符')).toHaveValue('dot')
  const conflict = builder.getByText('样例与规范不一致，请选择').locator('..')
  while (await conflict.count()) await conflict.first().getByRole('button', { name: '采用规范' }).click()
  await builder.getByLabel('固定页眉文字').fill('南京邮电大学硕士研究生学位论文')
  await builder.getByLabel('一级标题起页方式').selectOption('new-page')
  await builder.getByLabel('模板名称').fill('南京邮电大学 · 硕士排版验收')
  await builder.getByRole('button', { name: '编译 PDF 预览' }).click()
  await builder.getByRole('link', { name: '下载预览 PDF' }).waitFor({ timeout: 60_000 })
  await builder.getByRole('button', { name: '保存到我的模板' }).click()

  async function verifyVariant(title: string, stream: 'split' | 'parity') {
    await page.getByRole('button', { name: '使用模板', exact: true }).click()
    const importer = page.getByRole('dialog', { name: 'Import Word to TeX' })
    await importer.getByLabel('Project name').fill(title)
    await importer.getByLabel('Word manuscript').setInputFiles(join(graduateFixture!, 'manuscript.docx'))
    const response = page.waitForResponse(result => result.url().endsWith('/api/word/import') && result.request().method() === 'POST')
    await importer.getByRole('button', { name: 'Create TeX project' }).click()
    const converted = await response
    expect(converted.ok(), converted.ok() ? undefined : await converted.text()).toBe(true)
    const zip = await JSZip.loadAsync(await converted.body())
    const source = await zip.file('manuscript.tex')!.async('string')
    expect(source).toContain('\\CustomWordFront')
    expect(source).toContain('\\markboth{1 网络观测}{1 网络观测}')
    expect(source).toContain('图 1.1')
    expect(source).toContain('表 1.1')
    expect(source).not.toContain('图 1-8')
    expect(source).not.toContain('表 1-9')
    expect(await zip.file('word-layout-issues.json')!.async('string')).toContain('1 个单独出现的数字引文编号未匹配')
    await expect(page.getByRole('heading', { name: title })).toBeVisible()
    await page.getByRole('button', { name: 'Compile PDF', exact: true }).click()
    const panel = page.getByRole('region', { name: 'PDF Preview' })
    await expect(panel.getByRole('link', { name: 'Download PDF' })).toBeVisible({ timeout: 60_000 })
    const download = page.waitForEvent('download')
    await panel.getByRole('link', { name: 'Download PDF' }).click()
    await (await download).saveAs(info.outputPath('njupt-' + stream + '.pdf'))
  }

  await verifyVariant('南邮硕士 · 对开页眉', 'split')
  await page.goto('/research?section=templates&category=mine')
  await page.getByRole('button', { name: '编辑版式', exact: true }).click()
  const editor = page.getByRole('dialog', { name: '编辑 Word 版式' })
  await editor.getByLabel('模板名称').fill('单双页页眉验收版式')
  await editor.getByLabel('正文单双页页眉').selectOption('odd-chapter')
  await editor.getByLabel('页眉位置').selectOption('center')
  await editor.getByLabel('用于预览的 Word 稿件').setInputFiles(join(graduateFixture!, 'manuscript.docx'))
  await editor.getByRole('button', { name: '编译 PDF 预览' }).click()
  await editor.getByRole('link', { name: '下载预览 PDF' }).waitFor({ timeout: 60_000 })
  await editor.getByRole('button', { name: '另存为新版本' }).click()
  await verifyVariant('单双页交替样例', 'parity')
})
